"""Write oriented_cyl_01_results.html from the same producer outputs as make_results_md.py.

The page is the markdown rendered by make_results_md (same FINAL predicate, same refusals),
converted section by section: headings, pipe tables, bullet lists and paragraphs. Nothing is
recomputed; every number is a producer field. The source digests are printed in the footer.

    python make_results_html.py --stats ckpt/exp06/stats.json --h3 ckpt/exp06/h3.json \
        --gate ckpt/exp06/gate_g1.json [--out oriented_cyl_01_results.html]
"""
import argparse
import html
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_results_md as md  # noqa: E402

OUT = os.path.join(HERE, '..', 'oriented_cyl_01_results.html')
STYLE = """
body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;max-width:1100px;margin:2rem auto;padding:0 1rem;color:#1b1b1b;background:#fbfbf9}
h1{font-size:1.6rem}h2{font-size:1.2rem;margin-top:2rem;border-bottom:1px solid #ddd;padding-bottom:.2rem}
table{border-collapse:collapse;margin:.6rem 0;font-size:.86rem}th,td{border:1px solid #d5d5d0;padding:.3rem .5rem;text-align:left;vertical-align:top}
th{background:#efefea}code{background:#f0f0ec;padding:0 .2rem;border-radius:3px}
.verdict{font-weight:600}.note{color:#555;font-size:.9rem}footer{margin-top:2.5rem;font-size:.8rem;color:#666}
"""


def inline(text):
    """Escape, then restore the two inline markups the markdown uses: **bold** and `code`."""
    out = html.escape(text)
    while '**' in out:
        a = out.find('**')
        b = out.find('**', a + 2)
        if b < 0:
            break
        out = out[:a] + '<strong>' + out[a + 2:b] + '</strong>' + out[b + 2:]
    while '`' in out:
        a = out.find('`')
        b = out.find('`', a + 1)
        if b < 0:
            break
        out = out[:a] + '<code>' + out[a + 1:b] + '</code>' + out[b + 1:]
    return out


def table_html(lines):
    head = [c.strip() for c in lines[0].strip('|').split('|')]
    rows = [[c.strip() for c in line.strip('|').split('|')] for line in lines[2:]]
    out = ['<table><thead><tr>' + ''.join('<th>' + inline(c) + '</th>' for c in head) + '</tr></thead><tbody>']
    for row in rows:
        out.append('<tr>' + ''.join('<td>' + inline(c) + '</td>' for c in row) + '</tr>')
    out.append('</tbody></table>')
    return '\n'.join(out)


def to_html(markdown):
    lines = markdown.split('\n')
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        if line.startswith('# '):
            out.append('<h1>' + inline(line[2:]) + '</h1>')
        elif line.startswith('## '):
            out.append('<h2>' + inline(line[3:]) + '</h2>')
        elif line.startswith('|'):
            block = []
            while i < len(lines) and lines[i].startswith('|'):
                block.append(lines[i])
                i += 1
            out.append(table_html(block))
            continue
        elif line.startswith('- '):
            block = []
            while i < len(lines) and lines[i].startswith('- '):
                block.append('<li>' + inline(lines[i][2:]) + '</li>')
                i += 1
            out.append('<ul>' + '\n'.join(block) + '</ul>')
            continue
        elif line.strip():
            out.append('<p>' + inline(line) + '</p>')
        i += 1
    return '\n'.join(out)


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument('--stats', default=os.path.join(md.REPO, 'ckpt/exp06/stats.json'))
    parser.add_argument('--h3', default=os.path.join(md.REPO, 'ckpt/exp06/h3.json'))
    parser.add_argument('--gate', default=os.path.join(md.REPO, 'ckpt/exp06/gate_g1.json'))
    parser.add_argument('--out', default=OUT)
    args = parser.parse_args(argv)
    # Render the markdown to a temporary path through the same code path (same FINAL predicate).
    tmp = args.out + '.md.tmp'
    md.main(['--stats', args.stats, '--h3', args.h3, '--gate', args.gate, '--out', tmp])
    markdown = open(tmp).read()
    os.unlink(tmp)
    body = to_html(markdown)
    footer = ('<footer>Sources: stats.json {} · h3.json {} · gate_g1.json {} · generated by '
              'oriented_cyl_results_assets/make_results_html.py from the producer outputs only.</footer>'.format(
                  md.sha(args.stats), md.sha(args.h3), md.sha(args.gate)))
    page = ('<!doctype html><html lang="en"><head><meta charset="utf-8"><title>exp_06 oriented_cyl — results</title>'
            '<style>{}</style></head><body>{}\n{}</body></html>\n'.format(STYLE, body, footer))
    with open(args.out, 'w') as handle:
        handle.write(page)
    print('wrote', args.out, len(page), 'bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main())
