"""Offline exp_07 seen-protocol page: the same admission and tables, no scripts or fetches."""
from pathlib import Path

from tools.exp04_record import load_asset as exp04_asset
from tools.exp07_record import load_asset

md = load_asset('make_results_md')
page = exp04_asset('make_results_html')
CSS, esc, table_block = page.CSS, page.esc, page.table_block
TITLE = 'Seen-protocol results (exp_07)'


def main(argv=None):
    args, record, head = md.arguments(argv)
    identity = ('generated by make_results_html.py from ' +
                ', '.join(receipt['sha256'] for receipt in record['receipts']) + ' at ' + head)
    parts = ['<!doctype html><html lang="en"><meta charset="utf-8">'
             '<meta name="viewport" content="width=device-width, initial-scale=1">',
             '<title>' + esc(TITLE) + '</title><style>' + CSS + '</style><body><main>',
             '<p class="identity">' + esc(identity) + '</p>',
             '<h1>' + esc(TITLE) + '</h1>',
             '<p>' + esc(md.ROUNDING) + '</p>', '<p>' + esc(md.DESCRIPTIVE) + '</p>']
    blocks = list(md.tables(record, head))
    parts.extend(table_block(*block) for block in blocks[:-2])
    parts += ['<footer>'] + [table_block(*block) for block in blocks[-2:]] + ['</footer>']
    parts.append('</main></body></html>')
    Path(args.out).write_text('\n'.join(parts), encoding='utf-8')


if __name__ == '__main__':
    main()
